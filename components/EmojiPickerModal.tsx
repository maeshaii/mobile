interface EmojiPickerModalProps {
  visible: boolean;
  onClose: () => void;
  onEmojiSelected: (emoji: string) => void;
  keyboardHeight: number;
}

const EmojiPickerModal: React.FC<EmojiPickerModalProps> = ({
  visible,
  onClose,
  onEmojiSelected,
  keyboardHeight,
}) => {
  const [selectedCategory, setSelectedCategory] = React.useState('Smileys');

  if (!visible) return null;

  console.log('😊 EmojiPickerModal rendering with height:', keyboardHeight);
  
  return (
    <View style={[styles.container, { height: keyboardHeight }]}>
      {/* Header with keyboard button */}
      <View style={styles.header}>
        <Text style={styles.title}>Choose Emojis</Text>
        <TouchableOpacity onPress={onClose} style={styles.closeButton}>
          <FontAwesome name="keyboard-o" size={20} color="#666" />
        </TouchableOpacity>
      </View>

      {/* Category tabs */}
      <ScrollView 
        horizontal 
        showsHorizontalScrollIndicator={false}
        style={styles.categoryTabs}
      >
        {Object.keys(EMOJI_DATA).map((category) => (
          <TouchableOpacity
            key={category}
            onPress={() => setSelectedCategory(category)}
            style={[
              styles.categoryTab,
              selectedCategory === category && styles.categoryTabActive
            ]}
          >
            <Text style={[
              styles.categoryTabText,
              selectedCategory === category && styles.categoryTabTextActive
            ]}>
              {category}
            </Text>
          </TouchableOpacity>
        ))}
      </ScrollView>

      {/* Emoji grid */}
      <ScrollView 
        style={styles.emojiScroll}
        contentContainerStyle={styles.emojiScrollContent}
        showsVerticalScrollIndicator={true}
      >
        <View style={styles.emojiGrid}>
          {EMOJI_DATA[selectedCategory as keyof typeof EMOJI_DATA].map((emoji, index) => (
            <TouchableOpacity
              key={`${emoji}-${index}`}
              onPress={() => {
                console.log('Emoji selected:', emoji);
                onEmojiSelected(emoji);
              }}
              style={styles.emojiButton}
              activeOpacity={0.6}
            >
              <Text style={styles.emoji}>{emoji}</Text>
            </TouchableOpacity>
          ))}
        </View>
      </ScrollView>

      {/* Hint text */}
      <View style={styles.hintContainer}>
        <Text style={styles.hintText}>Tap keyboard icon to return to typing</Text>
      </View>
    </View>
  );
};

